package main

import (
	"apphost/modules/aspire"
	"log"
)

func main() {
	builder, err := aspire.CreateBuilder()
	if err != nil {
		log.Fatal(aspire.FormatError(err))
	}

	dbx := builder.AddDbx(&aspire.AddDbxOptions{Name: aspire.StringPtr("dbx")})
	dbx.WithHostPort(aspire.Float64Ptr(3310))
	_ = dbx.PrimaryEndpoint()
	if err := dbx.Err(); err != nil {
		log.Fatal(aspire.FormatError(err))
	}

	app, err := builder.Build()
	if err != nil {
		log.Fatal(aspire.FormatError(err))
	}
	if err := app.Run(); err != nil {
		log.Fatal(aspire.FormatError(err))
	}
}
