package main

import (
	"apphost/modules/aspire"
	"log"
)

func main() {
	builder, err := aspire.CreateBuilder()
	if err != nil {
		log.Fatal(aspire.FormatError(err))
	}

	dashboard := builder.AddStreamlitApp("dashboard", "../CommunityToolkit.Aspire.Hosting.Python.Extensions.AppHost.TypeScript/streamlit-app", "app.py")
	dashboard.WithExplicitStart()
	if err := dashboard.Err(); err != nil {
		log.Fatal(aspire.FormatError(err))
	}

	app, err := builder.Build()
	if err != nil {
		log.Fatal(aspire.FormatError(err))
	}
	if err := app.Run(); err != nil {
		log.Fatal(aspire.FormatError(err))
	}
}
