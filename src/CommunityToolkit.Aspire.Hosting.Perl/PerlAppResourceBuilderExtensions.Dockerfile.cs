    /// <summary>
    /// Builds the command arguments used as a container entrypoint based on
    /// the configured Perl entrypoint type.
    /// </summary>
    /// <param name="entrypointType">The entrypoint invocation mode.</param>
    /// <param name="entrypoint">The script/module/executable entrypoint.</param>
    /// <param name="apiSubcommand">Optional API subcommand, defaults to <c>daemon</c> for API mode.</param>
    /// <param name="useLocalLibPath">Whether to include local::lib include-path arguments.</param>
    /// <returns>The argument vector for Docker <c>ENTRYPOINT</c>.</returns>
    internal static string[] BuildContainerEntrypointArguments(
        EntrypointType entrypointType,
        string entrypoint,
        string? apiSubcommand,
        bool useLocalLibPath)
    {
        ArgumentException.ThrowIfNullOrEmpty(entrypoint);

        if (entrypointType == EntrypointType.Executable)
        {
            return [entrypoint];
        }

        List<string> args = ["perl"];
        if (useLocalLibPath)
        {
            args.Add("-Ilocal/lib/perl5");
        }

        switch (entrypointType)
        {
            case EntrypointType.Module:
                args.Add($"-M{entrypoint}");
                args.Add("-e");
                args.Add($"{entrypoint}->run()");
                break;

            case EntrypointType.API:
                args.Add(entrypoint);
                args.Add(string.IsNullOrWhiteSpace(apiSubcommand) ? "daemon" : apiSubcommand);
                break;

            default:
                args.Add(entrypoint);
                break;
        }

        return [.. args];
    }

    // Without these rules, `COPY . .` copies a host-built local/ (from `carton install` or WithLocalLib) over
    // the modules installed inside the image, along with .git and build artifacts.
    // See https://docs.docker.com/build/concepts/context/#filename-and-location.
    private static readonly string[] s_defaultBuildContextIgnoreRules =
    [
        "local",
        "blib",
        "_build",
        "pm_to_blib",
        ".git",
        ".gitignore",
        ".DS_Store",
        "**/.env",
        "**/.env.*",
        ".aspire",
        "aspire-output",
        "Dockerfile",
        "Dockerfile.*",
        "*.Dockerfile",
        "*.Dockerfile.dockerignore",
        ".dockerignore",
    ];

    /// <summary>
    /// Builds the per-Dockerfile <c>.dockerignore</c> content emitted next to a generated Perl Dockerfile.
    /// </summary>
    /// <param name="localLibPath">Optional local::lib path, relative to the application directory, to exclude in addition to <c>local</c>.</param>
    /// <returns>The ignore file content, using <c>\n</c> line endings.</returns>
    internal static string BuildContextIgnoreContent(string? localLibPath)
    {
        List<string> lines = ["# Generated by Aspire. Author <contextRoot>/.dockerignore to take over these rules."];
        lines.AddRange(s_defaultBuildContextIgnoreRules);

        if (localLibPath is not null)
        {
            ThrowIfLocalLibPathHasControlCharacters(localLibPath);

            if (NormalizeRelativeLocalLibPath(localLibPath) is { } normalized)
            {
                var rule = EscapeIgnoreRule(normalized);
                if (!lines.Contains(rule, StringComparer.Ordinal))
                {
                    lines.Insert(2, rule);
                }
            }
        }

        return string.Join('\n', lines) + "\n";
    }

    // Returns the path with '/' separators and without leading "./" or trailing '/', or null when it is
    // empty, ".", or rooted (and therefore outside the build context).
    private static string? NormalizeRelativeLocalLibPath(string localLibPath)
    {
        var normalized = localLibPath.Replace('\\', '/').Trim().TrimEnd('/');
        while (normalized.StartsWith("./", StringComparison.Ordinal))
        {
            normalized = normalized[2..];
        }

        return normalized.Length == 0 || normalized == "." || Path.IsPathRooted(normalized)
            ? null
            : normalized;
    }

    // A control character (such as a newline) would split the generated .dockerignore or Dockerfile line.
    private static void ThrowIfLocalLibPathHasControlCharacters(string localLibPath)
    {
        if (localLibPath.Any(char.IsControl))
        {
            throw new InvalidOperationException(
                "The local::lib path configured with WithLocalLib contains control characters and cannot be used in a generated Dockerfile or .dockerignore.");
        }
    }

    // Encodes a literal relative path as a .dockerignore rule. Backslash escapes are not portable
    // (Windows clients treat '\' as a path separator), so:
    // - glob metacharacters and a leading '!' (negation) become single-character classes: [*], [?], [[], [!];
    // - a leading '#' (comment) gets a '/' prefix, which Docker strips, keeping the rule an exact match.
    private static string EscapeIgnoreRule(string literalPath)
    {
        var builder = new StringBuilder(literalPath.Length + 2);
        var usesCharacterClass = false;
        for (var i = 0; i < literalPath.Length; i++)
        {
            var ch = literalPath[i];
            if (ch is '*' or '?' or '[' || (i == 0 && ch == '!'))
            {
                builder.Append('[').Append(ch).Append(']');
                usesCharacterClass = true;
            }
            else
            {
                builder.Append(ch);
            }
        }

        if (literalPath[0] == '#')
        {
            builder.Insert(0, '/');
        }

        // Rules containing '[' or ']' are compiled to a regular expression in which Docker leaves '^' unescaped,
        // so it acts as an anchor and the rule never matches.
        if (literalPath.Contains('^') && (usesCharacterClass || literalPath.Contains(']')))
        {
            throw new InvalidOperationException(
                $"The local::lib path '{literalPath}' configured with WithLocalLib cannot be expressed as a .dockerignore rule " +
                "because it combines '^' with '*', '?', '[', ']', or a leading '!'. Rename the directory, or add a .dockerignore " +
                "to the application directory to replace the generated rules.");
        }

        return builder.ToString();
    }

    // Maps the configured local::lib path to its location inside the generated image's /app working directory.
    private static string GetContainerLocalLibRoot(string localLibPath)
    {
        ThrowIfLocalLibPathHasControlCharacters(localLibPath);
        return $"/app/{NormalizeRelativeLocalLibPath(localLibPath) ?? localLibPath}";
    }

    private static bool IsShellSafe(string value) =>
        value.Length > 0 &&
        value.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is '/' or '.' or '_' or '-' or ':' or '@' or '%' or '+' or ',' or '=');

    // Single-quotes a value for the /bin/sh used by shell-form RUN instructions.
    private static string QuoteShellArgument(string value) =>
        IsShellSafe(value) ? value : $"'{value.Replace("'", "'\\''", StringComparison.Ordinal)}'";

    // Double-quotes an ENV value; inside quotes Docker treats '\' as the escape character and expands '$'.
    private static string QuoteDockerfileEnvValue(string value) =>
        IsShellSafe(value)
            ? value
            : $"\"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal).Replace("$", "\\$", StringComparison.Ordinal)}\"";

    /// <summary>
    /// Configures the Perl resource for publish (deployment) mode by adding
    /// <c>PublishAsDockerFile</c>. When the application directory has no authored <c>Dockerfile</c>,
    /// a Dockerfile tailored to the active package manager is generated along with a
    /// per-Dockerfile <c>.dockerignore</c> (unless an authored <c>.dockerignore</c> exists).
    /// </summary>
    /// <param name="resourceBuilder">The Perl resource builder being configured for publish mode.</param>
    /// <param name="entrypointType">The application entrypoint type.</param>
    /// <param name="entrypoint">The script/module/executable entrypoint value.</param>
    /// <param name="apiSubcommand">Optional API subcommand used for API entrypoints.</param>
    private static void ConfigurePublishMode(
        IResourceBuilder<PerlAppResource> resourceBuilder,
        EntrypointType entrypointType,
        string entrypoint,
        string? apiSubcommand)
    {
        var appDirectory = resourceBuilder.Resource.WorkingDirectory;

        resourceBuilder.PublishAsDockerFile(container =>
        {
            if (File.Exists(Path.Combine(appDirectory, "Dockerfile")))
            {
                return;
            }

#pragma warning disable ASPIREDOCKERFILEBUILDER001
            container.WithDockerfileBuilder(appDirectory, context => GeneratePerlDockerfile(context, appDirectory, entrypointType, entrypoint, apiSubcommand));
#pragma warning restore ASPIREDOCKERFILEBUILDER001
        });
    }

#pragma warning disable ASPIREDOCKERFILEBUILDER001
    private static Task GeneratePerlDockerfile(
        DockerfileBuilderCallbackContext context,
        string appDirectory,
        EntrypointType entrypointType,
        string entrypoint,
        string? apiSubcommand)
    {
        var resource = context.Resource;

        // Determine package manager strategy
        var packageManager = PerlPackageManager.Cpanm; // default for publish
        if (resource.TryGetLastAnnotation<PerlPackageManagerAnnotation>(out var pmAnnotation))
        {
            packageManager = pmAnnotation.PackageManager;
        }

        // Determine base image — allow user override via DockerfileBaseImageAnnotation
        var baseImage = "perl:5-slim";
        var buildImage = "perl:5";
        if (resource.TryGetLastAnnotation<DockerfileBaseImageAnnotation>(out var baseImageAnnotation))
        {
            if (baseImageAnnotation.RuntimeImage is { } runtimeImage)
            {
                baseImage = runtimeImage;
            }

            if (baseImageAnnotation.BuildImage is { } bi)
            {
                buildImage = bi;
            }
        }
#pragma warning restore ASPIREDOCKERFILEBUILDER001

        // Resolve local::lib path from annotation (if configured)
        string? localLibPath = null;
        if (resource.TryGetLastAnnotation<PerlLocalLibAnnotation>(out var localLibAnnotation))
        {
            localLibPath = localLibAnnotation.Path;
        }

        // A <dockerfile>.dockerignore replaces the context root's .dockerignore rather than merging with it,
        // so an authored one wins outright.
        if (resource.TryGetLastAnnotation<DockerfileBuildAnnotation>(out var dockerfileBuildAnnotation) &&
            !File.Exists(Path.Combine(appDirectory, ".dockerignore")))
        {
            dockerfileBuildAnnotation.BuildContextIgnoreContent ??= BuildContextIgnoreContent(localLibPath);
        }

        // Resolve carton deployment flag from annotation (default: true for publish)
        var cartonDeployment = true;
        if (resource.TryGetLastAnnotation<PerlCartonDeploymentAnnotation>(out var cartonDeploymentAnnotation))
        {
            cartonDeployment = cartonDeploymentAnnotation.UseDeployment;
        }

        var dependencyFiles = GetDependencyFiles(appDirectory);
        var requiredModules = resource.Annotations.OfType<PerlRequiredModuleAnnotation>()
            .DistinctBy(module => module.Name, StringComparer.Ordinal)
            .ToArray();

        switch (packageManager)
        {
            case PerlPackageManager.Carton:
                if (dependencyFiles.Length > 0 && !dependencyFiles.Contains("cpanfile", StringComparer.Ordinal))
                {
                    throw new DistributedApplicationException(
                        "Carton requires a cpanfile to install project dependencies. " +
                        "Add a cpanfile to the application directory or use WithCpanMinus() for Makefile.PL or Build.PL dependencies.");
                }

                BuildCartonDockerfile(context.Builder, entrypointType, entrypoint, apiSubcommand, baseImage, buildImage,
                    hasCpanfile: dependencyFiles.Contains("cpanfile", StringComparer.Ordinal),
                    hasSnapshot: File.Exists(Path.Combine(appDirectory, "cpanfile.snapshot")),
                    localLibPath, cartonDeployment);
                break;

            default:
                BuildCpanmDockerfile(context.Builder, entrypointType, entrypoint, apiSubcommand, baseImage,
                    dependencyFiles, localLibPath, requiredModules);
                break;
        }

        return Task.CompletedTask;
    }

    /// <summary>
    /// Builds a single-stage Dockerfile using cpanm for dependency installation.
    /// </summary>
    /// <param name="builder">The Dockerfile builder to append instructions to.</param>
    /// <param name="entrypointType">The application entrypoint type.</param>
    /// <param name="entrypoint">The script/module/executable entrypoint value.</param>
    /// <param name="apiSubcommand">Optional API subcommand used for API entrypoints.</param>
    /// <param name="baseImage">The base runtime image used for the generated Dockerfile.</param>
    /// <param name="dependencyFiles">Dependency manifests present in the application directory.</param>
    /// <param name="localLibPath">Optional local::lib path to install and resolve modules from.</param>
    /// <param name="requiredModules">Optional individual module requests to install after project dependencies.</param>
    internal static void BuildCpanmDockerfile(
        this DockerfileBuilder builder,
        EntrypointType entrypointType,
        string entrypoint,
        string? apiSubcommand,
        string baseImage,
        IReadOnlyList<string> dependencyFiles,
        string? localLibPath = null,
        IReadOnlyList<PerlRequiredModuleAnnotation>? requiredModules = null)
    {
        var localLibRoot = localLibPath is null ? null : GetContainerLocalLibRoot(localLibPath);
        var entrypointArgs = BuildContainerEntrypointArguments(entrypointType, entrypoint, apiSubcommand, useLocalLibPath: localLibRoot is not null);

        var stage = builder.From(baseImage)
            .WorkDir("/app");

        if (dependencyFiles.Count > 0 || requiredModules is { Count: > 0 })
        {
            stage.Run("cpanm App::cpanminus || true");
        }

        foreach (var dependencyFile in dependencyFiles)
        {
            stage.Copy(dependencyFile, "./");
        }

        if (dependencyFiles.Count > 0)
        {
            var installArgs = BuildProjectInstallArgs(PerlPackageManager.Cpanm, cartonDeployment: false, localLibRoot);
            stage.Run($"cpanm {string.Join(' ', installArgs.Select(QuoteShellArgument))}");
        }

        if (requiredModules is not null)
        {
            foreach (var module in requiredModules)
            {
                var installArgs = BuildInstallArgs(PerlPackageManager.Cpanm, module.Name, module.Force, module.SkipTest, localLibRoot);
                stage.Run($"cpanm {string.Join(' ', installArgs.Select(QuoteShellArgument))}");
            }
        }

        stage.Copy(".", ".");

        if (localLibRoot is not null)
        {
            stage.Env("PERL5LIB", QuoteDockerfileEnvValue($"{localLibRoot}/lib/perl5"))
                .Env("PERL_LOCAL_LIB_ROOT", QuoteDockerfileEnvValue(localLibRoot));
        }

        stage.Entrypoint(entrypointArgs);
    }

    /// <summary>
    /// Builds a multi-stage Dockerfile using Carton for reproducible dependency resolution.
    /// </summary>
    /// <param name="builder">The Dockerfile builder to append instructions to.</param>
    /// <param name="entrypointType">The application entrypoint type.</param>
    /// <param name="entrypoint">The script/module/executable entrypoint value.</param>
    /// <param name="apiSubcommand">Optional API subcommand used for API entrypoints.</param>
    /// <param name="runtimeImage">The runtime-stage image.</param>
    /// <param name="buildImage">The build-stage image.</param>
    /// <param name="hasCpanfile">Whether the application directory contains a cpanfile.</param>
    /// <param name="hasSnapshot">Whether the application directory contains a cpanfile.snapshot.</param>
    /// <param name="localLibPath">Optional local::lib path to expose in the runtime stage.</param>
    /// <param name="cartonDeployment">Whether to use <c>carton install --deployment</c>.</param>
    internal static void BuildCartonDockerfile(
        this DockerfileBuilder builder,
        EntrypointType entrypointType,
        string entrypoint,
        string? apiSubcommand,
        string runtimeImage,
        string buildImage,
        bool hasCpanfile,
        bool hasSnapshot,
        string? localLibPath = null,
        bool cartonDeployment = true)
    {
        if (hasCpanfile && cartonDeployment && !hasSnapshot)
        {
            throw new DistributedApplicationException(
                "carton install --deployment requires a cpanfile.snapshot file. " +
                "Run 'carton install' first to generate the snapshot, then commit it to source control, " +
                "or use WithProjectDependencies(cartonDeployment: false).");
        }

        var localLibRoot = localLibPath is null ? null : GetContainerLocalLibRoot(localLibPath);
        var entrypointArgs = BuildContainerEntrypointArguments(entrypointType, entrypoint, apiSubcommand, useLocalLibPath: true);

        var cartonInstallCommand = cartonDeployment
            ? "carton install --deployment"
            : "carton install";

        var buildStage = builder.From(buildImage, "build")
            .WorkDir("/app");

        if (hasCpanfile)
        {
            buildStage.Run("cpanm Carton")
                .Copy("cpanfile", "./");

            if (hasSnapshot)
            {
                buildStage.Copy("cpanfile.snapshot", "./");
            }

            buildStage.Run(cartonInstallCommand);
        }

        buildStage.Copy(".", ".");

        var runtimeStage = builder.From(runtimeImage)
            .WorkDir("/app")
            .CopyFrom("build", "/app", "/app");

        if (localLibRoot is not null)
        {
            runtimeStage.Env("PERL5LIB", QuoteDockerfileEnvValue($"{localLibRoot}/lib/perl5"))
                .Env("PERL_LOCAL_LIB_ROOT", QuoteDockerfileEnvValue(localLibRoot));
        }

        runtimeStage.Entrypoint(entrypointArgs);
    }
}
