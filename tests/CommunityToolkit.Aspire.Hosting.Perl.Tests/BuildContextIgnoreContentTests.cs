using Aspire.Hosting;

namespace CommunityToolkit.Aspire.Hosting.Perl.Tests;

public class BuildContextIgnoreContentTests
{
    [Fact]
    public void BuildContextIgnoreContent_Default_ExcludesHostBuildArtifacts()
    {
        var content = PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath: null);
        var rules = ReadRules(content);

        Assert.StartsWith("# Generated by Aspire.", content);
        Assert.Contains("local", rules);
        Assert.Contains("blib", rules);
        Assert.Contains("_build", rules);
        Assert.Contains(".git", rules);
        Assert.Contains("*.Dockerfile.dockerignore", rules);
        Assert.DoesNotContain("cpanfile", rules);
        Assert.DoesNotContain("cpanfile.snapshot", rules);
    }

    [Fact]
    public void BuildContextIgnoreContent_UsesLfLineEndings()
    {
        var content = PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath: "vendor/perl5");

        Assert.DoesNotContain('\r', content);
        Assert.EndsWith("\n", content);
    }

    [Theory]
    [InlineData("vendor/perl5")]
    [InlineData("./vendor/perl5/")]
    [InlineData(".\\vendor\\perl5")]
    [InlineData(" vendor/perl5 ")]
    public void BuildContextIgnoreContent_WithLocalLibPath_AddsNormalizedPathOnce(string localLibPath)
    {
        var rules = ReadRules(PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath));

        Assert.Single(rules, rule => rule == "vendor/perl5");
        Assert.Contains("local", rules);
    }

    [Theory]
    [InlineData("local")]
    [InlineData("./local/")]
    [InlineData(".")]
    [InlineData("")]
    public void BuildContextIgnoreContent_WithDefaultOrEmptyLocalLibPath_MatchesDefault(string localLibPath)
    {
        var expected = PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath: null);

        Assert.Equal(expected, PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath));
        Assert.Single(ReadRules(expected), rule => rule == "local");
    }

    [Fact]
    public void BuildContextIgnoreContent_Default_ExcludesEnvFilesAtAnyDepth()
    {
        var rules = ReadRules(PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath: null));

        Assert.Contains("**/.env", rules);
        Assert.Contains("**/.env.*", rules);
        Assert.DoesNotContain(".env", rules);
        Assert.DoesNotContain(".env.*", rules);
    }

    [Theory]
    [InlineData("#vendor", "/#vendor")]
    [InlineData("#ve^ndor", "/#ve^ndor")]
    [InlineData("!vendor", "[!]vendor")]
    [InlineData("vendor/perl[5]", "vendor/perl[[]5]")]
    [InlineData("vendor/*", "vendor/[*]")]
    [InlineData("vendor/perl?", "vendor/perl[?]")]
    [InlineData("vendor/#perl!", "vendor/#perl!")]
    [InlineData("ve^ndor", "ve^ndor")]
    public void BuildContextIgnoreContent_WithSpecialCharactersInLocalLibPath_EncodesLiteralPath(string localLibPath, string expectedRule)
    {
        var rules = ReadRules(PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath));

        Assert.Single(rules, rule => rule == expectedRule);
        Assert.DoesNotContain(localLibPath, rules.Where(rule => rule != expectedRule));
    }

    [Theory]
    [InlineData("ve^ndor/*")]
    [InlineData("ve^ndor[5]")]
    [InlineData("ve^ndor]")]
    [InlineData("!ve^ndor")]
    public void BuildContextIgnoreContent_WithCaretInPatternRule_Throws(string localLibPath)
    {
        var exception = Assert.Throws<InvalidOperationException>(
            () => PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath));

        Assert.Contains("'^'", exception.Message);
    }

    [Theory]
    [InlineData("vendor\nperl5")]
    [InlineData("vendor\rperl5")]
    [InlineData("vendor\tperl5")]
    public void BuildContextIgnoreContent_WithControlCharactersInLocalLibPath_Throws(string localLibPath)
    {
        Assert.Throws<InvalidOperationException>(
            () => PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath));
    }

    [Fact]
    public void BuildContextIgnoreContent_WithRootedLocalLibPath_IgnoresIt()
    {
        var rooted = OperatingSystem.IsWindows() ? @"C:\perl\lib" : "/opt/perl/lib";

        Assert.Equal(
            PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(localLibPath: null),
            PerlAppResourceBuilderExtensions.BuildContextIgnoreContent(rooted));
    }

    private static string[] ReadRules(string content) =>
        content.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
}
